type ScheduleType = {
  date: string,
  games: {
    awayTeam: string,
    homeTeam: string,
  }[]
}

export const createSchedule = () => {
  const schedule: ScheduleType[] = [];
  let date = "";
  let weekday = "";
  let month = "";
  let dayOfMonth = "";

  let games: {
    awayTeam: string,
    homeTeam: string,
  }[] = [];

  let awayTeam = "";
  let homeTeam = "";

  basicData.forEach((input) => {
    if(input.includes(",")){

      schedule.push({
        date,
        games
      });

      games = [];

      const bd = input.split(" ");
      dayOfMonth = bd.reverse()[0] ?? "";
      month = bd.reverse()[1] ?? "";
      weekday = bd.reverse()[2] ?? "";
      date = weekday + " " + month + " " + dayOfMonth;
    } else if (input.includes("@")) {

      const bd = input.split(" @ ");
      awayTeam = bd[0] ?? "";
      homeTeam = bd[1] ?? "";
      games.push({
        awayTeam,
        homeTeam
      })
    }
  })

  console.log(schedule);
}

